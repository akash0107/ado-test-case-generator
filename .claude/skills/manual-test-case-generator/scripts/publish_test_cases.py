#!/usr/bin/env python3
"""Create Azure DevOps "Test Case" work items from a validated test-case JSON
document, link each one to the story ("Tests" link), and optionally add them
to a Test Plan suite.

SAFE BY DEFAULT: without --apply this is a dry run that prints what would be
created and makes no changes in Azure DevOps.

Idempotent: created IDs are recorded in <input>.published.json, and test cases
already recorded there are skipped on later runs.

Usage:
    python3 publish_test_cases.py test-cases/12345/test-cases.json             # dry run
    python3 publish_test_cases.py test-cases/12345/test-cases.json --apply
    python3 publish_test_cases.py test-cases/12345/test-cases.json --apply --plan-id 10 --suite-id 42

Exit codes: 0 success, 1 Azure DevOps or validation error, 2 configuration/usage error.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional
from xml.sax.saxutils import escape as xml_escape

from ado_client import AdoClient, AdoConfig, AdoConfigError, AdoError
from testcase_schema import load, validate

GENERATOR_TAG = "AI-Generated"
LINK_COMMENT = "Generated by manual-test-case-generator skill"


def _rich_text(text: str) -> str:
    body = html.escape(text).replace("\n", "<BR/>")
    body = re.sub(r"\*\*(.+?)\*\*", r"<B>\1</B>", body)
    return "<DIV><P>" + body + "</P></DIV>"


def build_steps_xml(steps: list[dict]) -> str:
    """Serialize steps into the Microsoft.VSTS.TCM.Steps XML format."""
    parts = []
    for step_id, step in enumerate(steps, start=1):
        expected = step.get("expected", "")
        step_type = "ValidateStep" if expected else "ActionStep"
        parts.append(
            f'<step id="{step_id}" type="{step_type}">'
            f'<parameterizedString isformatted="true">{xml_escape(_rich_text(step["action"]))}</parameterizedString>'
            f'<parameterizedString isformatted="true">{xml_escape(_rich_text(expected))}</parameterizedString>'
            "<description/></step>"
        )
    return f'<steps id="0" last="{len(steps)}">' + "".join(parts) + "</steps>"


def build_description(tc: dict) -> str:
    def section(title: str, items: list[str]) -> str:
        if not items:
            return ""
        return f"<p><b>{title}</b></p><ul>" + "".join(f"<li>{html.escape(i)}</li>" for i in items) + "</ul>"

    data = [f"{d['name']}: {d['value']}" for d in tc.get("test_data", [])]
    return (
        f"<p><b>Objective:</b> {html.escape(tc['objective'])}</p>"
        f"<p><b>Type:</b> {html.escape(tc['type'])} &nbsp;|&nbsp; <b>Technique:</b> {html.escape(tc['technique'])}"
        f" &nbsp;|&nbsp; <b>Covers:</b> {html.escape(', '.join(tc['requirement_refs']))}</p>"
        + section("Preconditions", tc.get("preconditions", []))
        + section("Test data", data)
        + section("Postconditions", tc.get("postconditions", []))
        + f"<p><i>Source ID: {html.escape(tc['id'])}</i></p>"
    )


def build_patch(tc: dict, story_id: int, config: AdoConfig, area: Optional[str], iteration: Optional[str], assigned_to: Optional[str]) -> list[dict]:
    tags = "; ".join(dict.fromkeys([GENERATOR_TAG, f"Story-{story_id}", tc["type"], *tc.get("tags", [])]))
    patch = [
        {"op": "add", "path": "/fields/System.Title", "value": re.sub(r"\*\*(.+?)\*\*", r"\1", tc["title"])},
        {"op": "add", "path": "/fields/Microsoft.VSTS.TCM.Steps", "value": build_steps_xml(tc["steps"])},
        {"op": "add", "path": "/fields/System.Description", "value": build_description(tc)},
        {"op": "add", "path": "/fields/Microsoft.VSTS.Common.Priority", "value": tc["priority"]},
        {"op": "add", "path": "/fields/System.Tags", "value": tags},
        {
            "op": "add",
            "path": "/relations/-",
            "value": {
                "rel": "Microsoft.VSTS.Common.TestedBy-Reverse",
                "url": config.api_work_item_url(story_id),
                "attributes": {"comment": LINK_COMMENT},
            },
        },
    ]
    if area:
        patch.append({"op": "add", "path": "/fields/System.AreaPath", "value": area})
    if iteration:
        patch.append({"op": "add", "path": "/fields/System.IterationPath", "value": iteration})
    if assigned_to:
        patch.append({"op": "add", "path": "/fields/System.AssignedTo", "value": assigned_to})
    return patch


def load_ledger(path: Path) -> dict:
    if path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"story_id": None, "published": {}}


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", type=Path, help="Path to the validated test-case JSON document")
    parser.add_argument("--apply", action="store_true", help="Actually create work items (default is a dry run)")
    parser.add_argument("--only", nargs="+", metavar="TC_ID", help="Publish only these test case ids")
    parser.add_argument("--area-path", help="Override Area Path (default: the story's)")
    parser.add_argument("--iteration-path", help="Override Iteration Path (default: the story's)")
    parser.add_argument("--assigned-to", help="Assign created test cases to this user (email or display name)")
    parser.add_argument("--plan-id", type=int, help="Test Plan id to add the test cases to")
    parser.add_argument("--suite-id", type=int, help="Test Suite id to add the test cases to (requires --plan-id)")
    args = parser.parse_args(argv)

    if bool(args.plan_id) != bool(args.suite_id):
        parser.error("--plan-id and --suite-id must be given together")
    if not args.input.is_file():
        print(f"ERROR: {args.input} does not exist.", file=sys.stderr)
        return 2

    try:
        doc = load(args.input)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    report = validate(doc)
    if not report.ok:
        for error in report.errors:
            print(f"ERROR: {error}")
        print("Refusing to publish an invalid document. Run export_test_cases.py --validate-only first.")
        return 1

    story_id = doc["story"]["id"]
    ledger_path = args.input.with_suffix(".published.json")
    ledger = load_ledger(ledger_path)
    cases = [tc for tc in doc["test_cases"] if not args.only or tc["id"] in args.only]
    if args.only:
        unknown = set(args.only) - {tc["id"] for tc in cases}
        if unknown:
            print(f"ERROR: unknown test case id(s): {', '.join(sorted(unknown))}", file=sys.stderr)
            return 2
    pending = [tc for tc in cases if tc["id"] not in ledger["published"]]
    skipped = [tc["id"] for tc in cases if tc["id"] in ledger["published"]]

    try:
        config = AdoConfig.from_env()
    except AdoConfigError as exc:
        if args.apply:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2
        config = AdoConfig(org_url="https://dev.azure.com/<ADO_ORG_URL not set>", project="<ADO_PROJECT>", pat="")

    mode = "APPLY" if args.apply else "DRY RUN"
    print(f"[{mode}] Story {story_id}: {len(pending)} test case(s) to create, {len(skipped)} already published.")
    for tc_id in skipped:
        print(f"  skip  {tc_id} -> ADO #{ledger['published'][tc_id]}")

    if not args.apply:
        for tc in pending:
            print(f"  would create  {tc['id']}  P{tc['priority']}  {len(tc['steps'])} steps  '{tc['title']}'")
        area = args.area_path or "(story's area path)"
        iteration = args.iteration_path or "(story's iteration path)"
        print(f"  area: {area} | iteration: {iteration} | link: Tests -> #{story_id}")
        if args.plan_id:
            print(f"  would add to plan {args.plan_id}, suite {args.suite_id}")
        print("No changes made. Re-run with --apply after the user confirms.")
        return 0

    client = AdoClient(config)
    created: list[int] = []
    try:
        story = client.get_work_item(story_id)["fields"]
        area = args.area_path or story.get("System.AreaPath")
        iteration = args.iteration_path or story.get("System.IterationPath")
        for tc in pending:
            result = client.create_work_item("Test Case", build_patch(tc, story_id, config, area, iteration, args.assigned_to))
            ado_id = result["id"]
            created.append(ado_id)
            ledger["story_id"] = story_id
            ledger["published"][tc["id"]] = ado_id
            ledger["updated_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
            ledger_path.write_text(json.dumps(ledger, indent=2) + "\n", encoding="utf-8")
            print(f"  created  {tc['id']} -> ADO #{ado_id}  {config.web_url(ado_id)}")
        if args.plan_id and created:
            client.add_test_cases_to_suite(args.plan_id, args.suite_id, created)
            print(f"  added {len(created)} test case(s) to plan {args.plan_id}, suite {args.suite_id}")
    except AdoError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        if created:
            print(f"{len(created)} test case(s) were created before the failure and are recorded in {ledger_path}.")
        return 1

    print(f"Done. Created {len(created)} test case(s). Ledger: {ledger_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
